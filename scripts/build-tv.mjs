// Builds the TV host as a standalone web app for each TV store.
//   node scripts/build-tv.mjs <webos|tizen|android|all>
// Requires HUDDLE_SERVER_URL (the hosted hub, e.g. https://huddle.example.com).
// Spec: specs/002-tv-store-apps/design.md
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const meta = pkg.huddle;
const PLATFORMS = ['webos', 'tizen', 'android'];

function fail(msg) { console.error(`build-tv: ${msg}`); process.exit(1); }

const arg = process.argv[2] || 'all';
const targets = arg === 'all' ? PLATFORMS : [arg];
if (!targets.every(t => PLATFORMS.includes(t))) fail(`unknown platform "${arg}". Use one of: ${PLATFORMS.join(', ')}, all`);

const serverUrl = String(process.env.HUDDLE_SERVER_URL || '').replace(/\/$/, '');
if (!serverUrl) fail('set HUDDLE_SERVER_URL to the hosted hub, e.g. HUDDLE_SERVER_URL=https://huddle.example.com');
let parsed;
try { parsed = new URL(serverUrl); } catch { fail(`HUDDLE_SERVER_URL is not a valid URL: ${serverUrl}`); }
if (parsed.protocol !== 'https:') console.warn('build-tv: warning: HUDDLE_SERVER_URL is not https. Stores reject cleartext traffic; use this only for local testing.');

// Store versions must be numeric x.y.z.
if (!/^\d+\.\d+\.\d+$/.test(pkg.version)) fail(`package.json version must be x.y.z for TV stores, got ${pkg.version}`);

const fill = (text, vars) => text.replace(/\{\{(\w+)\}\}/g, (m, k) => {
  if (!(k in vars)) fail(`template variable {{${k}}} has no value`);
  return vars[k];
});

for (const platform of targets) {
  const out = join(root, 'dist', platform);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(join(out, 'socket.io'), { recursive: true });

  // TV host page becomes index.html; everything else keeps its relative path.
  // The PWA manifest is web-only (the store package has its own), so drop the link.
  const html = readFileSync(join(root, 'public', 'tv.html'), 'utf8').replace(/<link rel="manifest"[^>]*>\r?\n?/, '');
  writeFileSync(join(out, 'index.html'), html);
  for (const f of ['tv.css', 'tv.js', 'shared.js', 'platform.js', 'icon.svg']) cpSync(join(root, 'public', f), join(out, f));
  cpSync(join(root, 'public', 'games'), join(out, 'games'), { recursive: true });
  cpSync(join(root, 'node_modules', 'socket.io', 'client-dist', 'socket.io.min.js'), join(out, 'socket.io', 'socket.io.js'));
  writeFileSync(join(out, 'config.js'),
    `// Generated by scripts/build-tv.mjs. Do not edit.\nwindow.HUDDLE_CONFIG = ${JSON.stringify({ serverUrl, platform, version: pkg.version })};\n`);

  const vars = { ...meta, version: pkg.version, serverUrl, serverOrigin: parsed.origin, serverHost: parsed.host };
  const tplDir = join(root, 'platforms', platform === 'android' ? 'android-tv' : platform);
  if (platform === 'webos') {
    writeFileSync(join(out, 'appinfo.json'), fill(readFileSync(join(tplDir, 'appinfo.json'), 'utf8'), vars));
    for (const f of ['icon.png', 'largeIcon.png', 'splash.png']) cpSync(join(root, 'assets', 'generated', f), join(out, f));
  } else if (platform === 'tizen') {
    writeFileSync(join(out, 'config.xml'), fill(readFileSync(join(tplDir, 'config.xml'), 'utf8'), vars));
    cpSync(join(root, 'assets', 'generated', 'tizen-icon.png'), join(out, 'icon.png'));
  }
  const missing = ['index.html', 'config.js', 'socket.io/socket.io.js'].filter(f => !existsSync(join(out, f)));
  if (missing.length) fail(`${platform}: missing ${missing.join(', ')}`);
  console.log(`build-tv: ${platform} -> dist/${platform} (server ${serverUrl})`);
}
