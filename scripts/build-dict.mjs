// Builds public/content/dict.js, the Word Grid dictionary (spec 004 R2).
//   npm run dict
// Source: SCOWL size <= 60 (common words; no obscure Scrabble-only words) via the
// wordlist-english package, minus a profanity list (badwords-list). The output is committed,
// so the app and CI never need these dev dependencies at runtime.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'package.json'));
const src = join(root, 'node_modules', 'wordlist-english');
const LEVELS = [10, 20, 35, 40, 50, 55, 60];
const DIALECTS = ['english', 'american', 'british'];

const blocked = new Set(require('badwords-list').array.map(w => String(w).toLowerCase()));
const words = new Set();
for (const d of DIALECTS) for (const lv of LEVELS) {
  const f = join(src, `${d}-words-${lv}.json`);
  if (!existsSync(f)) continue;
  for (const w of JSON.parse(readFileSync(f, 'utf8'))) {
    if (!/^[a-z]{3,16}$/.test(w)) continue; // lowercase only: no proper nouns, no apostrophes
    if (blocked.has(w) || blocked.has(w.replace(/(es|s)$/, ''))) continue;
    words.add(w);
  }
}
const list = [...words].sort();
const notice = readFileSync(join(src, 'Copyright'), 'utf8').split('\n').slice(0, 13).map(l => '// ' + l).join('\n');
writeFileSync(join(root, 'public', 'content', 'dict.js'),
  `// Generated by scripts/build-dict.mjs. Do not edit. ${list.length} words.\n` +
  `// Word list from SCOWL (http://wordlist.aspell.net/), size <= 60:\n${notice}\n` +
  `(function (C) { C.dict = ${JSON.stringify(list.join(' '))}; })(window.HUDDLE_CONTENT = window.HUDDLE_CONTENT || {});\n`);
console.log(`build-dict: ${list.length} words -> public/content/dict.js`);
